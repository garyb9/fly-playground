export function flyName(existing: ReadonlySet<string>, random = Math.random): string {
  const start = Math.floor(random() * FIRST.length * LAST.length);
  for (let offset = 0; offset < FIRST.length * LAST.length; offset++) {
    const n = (start + offset) % (FIRST.length * LAST.length);
    const name = `${FIRST[Math.floor(n / LAST.length)]} ${LAST[n % LAST.length]}`;
    if (!existing.has(name)) return name;
  }
  return `Alpha Metatron ${existing.size + 1}`;
}
